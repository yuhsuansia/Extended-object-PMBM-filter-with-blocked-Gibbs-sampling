function motionModel = getConstantVelocityModel(scanTime, sigmaAcc)
%GETCONSTANTVELOCITYMODEL Build the 2-D constant-velocity transition and noise matrices.
dt  = scanTime;
dt2 = dt*dt;
dt3 = dt2*dt;

motionModel.A = [ ...
    1, 0, dt, 0; ...
    0, 1, 0, dt; ...
    0, 0, 1,  0; ...
    0, 0, 0,  1];

q11 = dt3/3;
q12 = dt2/2;
q22 = dt;

s2 = sigmaAcc * sigmaAcc;

motionModel.Q = s2 * [ ...
    q11, 0,   q12, 0; ...
    0,   q11, 0,   q12; ...
    q12, 0,   q22, 0; ...
    0,   q12, 0,   q22 ];
end
